import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';
import { keccak256, toHex } from 'viem';
const root=fileURLToPath(new URL('../',import.meta.url));
const sources={};
function add(path){if(sources[path])return;const content=readFileSync(resolve(root,path.startsWith('@')?'node_modules/'+path:path),'utf8');sources[path]={content};for(const match of content.matchAll(/import\s+(?:[^;]*?from\s+)?['"]([^'"]+)['"]/g)){add(match[1].startsWith('.')?posix.normalize(posix.join(posix.dirname(path),match[1])):match[1]);}}
add('contracts/SellerFeeRouter.sol');
if(!solc.version().startsWith('0.8.30+'))throw Error('Expected pinned Solidity 0.8.30');
const ordered=Object.fromEntries(Object.entries(sources).sort(([a],[b])=>a.localeCompare(b)));
const settings={optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'paris',metadata:{bytecodeHash:'none'},outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}};
const standardInput={language:'Solidity',sources:ordered,settings};
const compiled=JSON.parse(solc.compile(JSON.stringify(standardInput)));
for(const e of compiled.errors??[])if(e.severity==='error')throw Error(e.formattedMessage);
const contract=compiled.contracts['contracts/SellerFeeRouter.sol'].SellerFeeRouter;
const deployedBytecode='0x'+contract.evm.deployedBytecode.object;
const bytecodeHash=keccak256('0x'+contract.evm.bytecode.object);
const sourceHash=keccak256(toHex(JSON.stringify(standardInput)));
const runtimeHash=keccak256(deployedBytecode);
const artifact={abi:contract.abi,bytecode:'0x'+contract.evm.bytecode.object,deployedBytecode,runtimeHash,sourceHash,bytecodeHash,compiler:solc.version(),settings,standardInput};
writeFileSync(resolve(root,'lib/platform-fee-bytecode.json'),JSON.stringify(artifact,null,2)+'\n');
writeFileSync(resolve(root,'lib/platform-fee-runtime.ts'),`// Generated by scripts/build-platform-fee.mjs. Do not edit.\nexport const PLATFORM_FEE_RUNTIME_HASH = "${runtimeHash}" as const;\nexport const PLATFORM_FEE_SOURCE_HASH = "${sourceHash}" as const;\nexport const PLATFORM_FEE_BYTECODE_HASH = "${bytecodeHash}" as const;\n`);
console.log(`Compiled SellerFeeRouter: ${deployedBytecode.length/2-1} runtime bytes; ${runtimeHash}`);
